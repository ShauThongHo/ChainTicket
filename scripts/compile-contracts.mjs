#!/usr/bin/env node
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import solc from "solc";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "contracts");
const outDir = join(dir, "artifacts");
mkdirSync(outDir, { recursive: true });

const files = ["EventVault.sol", "EventMarketplace.sol", "DemoBank.sol", "TicketCollection.sol"];
const sources = {};
for (const name of files) {
  sources[name] = { content: readFileSync(join(dir, name), "utf8") };
}

const input = {
  language: "Solidity",
  sources,
  settings: {
    optimizer: { enabled: true, runs: 200 },
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } },
  },
};

function findImports(path) {
  const candidates = [join(root, "node_modules", path), join(dir, path)];
  for (const p of candidates) {
    if (existsSync(p)) return { contents: readFileSync(p, "utf8") };
  }
  return { error: `File not found: ${path}` };
}

const output = JSON.parse(solc.compile(JSON.stringify(input), { import: findImports }));
if (output.errors?.some((e) => e.severity === "error")) {
  console.error(output.errors.filter((e) => e.severity === "error"));
  process.exit(1);
}

const artifacts = {};
for (const name of files) {
  const contracts = output.contracts[name];
  for (const [cname, art] of Object.entries(contracts)) {
    artifacts[cname] = {
      abi: art.abi,
      bytecode: `0x${art.evm.bytecode.object}`,
    };
  }
}

const json = `${JSON.stringify(artifacts, null, 2)}\n`;
writeFileSync(join(outDir, "core.json"), json);
writeFileSync(join(root, "src/lib/abi/core.json"), json);
writeFileSync(
  join(root, "src/lib/abi/artifacts.ts"),
  `/* generated by scripts/compile-contracts.mjs — do not edit */\nexport const artifacts = ${JSON.stringify(artifacts, null, 2)} as const;\n`,
);
console.log("wrote", Object.keys(artifacts).join(", "));
